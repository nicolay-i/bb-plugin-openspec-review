import assert from "node:assert/strict";
import Database from "better-sqlite3";
import { Store, migrations } from "../src/store.ts";
import { dictionaries, en, plural, resolveLanguage, ru } from "../src/i18n.ts";
const db = new Database(":memory:");
for (const sql of migrations) db.exec(sql);
const store = new Store(db);
const doc = store.observe("ctx", "openspec/specs/auth/spec.md", false, "v1");
const first = store.create(doc.id, { kind: "md-text", quote: "Access", prefix: "", suffix: "" }, "Clarify this");
assert.equal(first.status, "open");
const second = store.create(doc.id, { kind: "doc" }, "Whole doc");
assert.equal(second.seq, 2);
assert.equal(store.edit(first.id, "Clarify more").body, "Clarify more");
store.markSent([first.id], "chat-a");
assert.throws(() => store.edit(first.id, "late"), /comment_not_editable/);
const queued = store.create(doc.id, { kind: "doc" }, "Queued");
store.markSent([queued.id], "chat-a", "q1");
assert.equal(store.comment(queued.id).status, "queued");
assert.ok(store.cancelled("q1"));
assert.deepEqual([store.comment(queued.id).status, store.comment(queued.id).sentThreadId], ["open", null]);
store.markSent([queued.id], "chat-a", "q2");
assert.ok(store.dispatched("q2")); assert.ok(!store.cancelled("q2"));
assert.equal(store.comment(queued.id).status, "sent");
store.remove(queued.id);
assert.deepEqual(store.reviewStats("ctx", [doc.path, "openspec/none.md"]), [{ path: doc.path, open: 1, sent: 1 }, { path: "openspec/none.md", open: 0, sent: 0 }]);
assert.equal(store.close(first.id).status, "closed");
store.remove(second.id);
assert.deepEqual(store.comments(doc.id).map(c => c.id), [first.id]);
assert.throws(() => store.comment(second.id), /comment_not_found/);
assert.equal(store.observe("ctx", doc.path, false, "v2").id, doc.id);
store.observe("ctx", doc.path, true, "");
assert.equal(store.comments(doc.id)[0].id, first.id);
assert.throws(() => store.create(doc.id, { kind: "doc" }, "missing"), /document_missing/);
const newDoc = store.observe("ctx", doc.path, false, "v3");
assert.notEqual(newDoc.id, doc.id);
assert.equal(store.comments(newDoc.id).length, 0);
assert.deepEqual(store.reviewStats("ctx", [doc.path]), [{ path: doc.path, open: 0, sent: 0 }], "stats count only the live generation");
const archive = store.observe("ctx", "openspec/changes/archive/2026-old/spec.md", false, "v2");
assert.notEqual(archive.id, doc.id);
assert.equal(store.comments(archive.id).length, 0);
const otherHost = store.observe("other", doc.path, false, "v3");
assert.notEqual(otherHost.id, newDoc.id);
for (const [code, dict] of Object.entries(dictionaries)) {
  assert.deepEqual(Object.keys(dict).sort(), Object.keys(en).sort(), code);
  assert.ok(Object.values(dict).every(value => value.trim().length > 0), code);
  assert.equal(dict.locale, code);
  assert.match(plural(dict, 2, dict.commentForms), /^2 \S/, code);
}
assert.equal(resolveLanguage("auto", ["de-AT", "en"]), "de");
assert.equal(resolveLanguage("auto", ["zh-TW"]), "zh-CN");
assert.equal(resolveLanguage("auto", ["pt-PT", "ru"]), "pt-BR");
assert.equal(resolveLanguage("auto", ["ar"]), "en");
assert.equal(resolveLanguage("ru", ["de"]), "ru");
assert.equal(resolveLanguage(undefined, []), "en");
assert.deepEqual([1, 2, 5, 21].map(n => plural(ru, n, ru.commentForms)), ["1 комментарий", "2 комментария", "5 комментариев", "21 комментарий"]);
assert.deepEqual([1, 2].map(n => plural(en, n, en.commentForms)), ["1 comment", "2 comments"]);
db.close();
// Old data maps onto the simplified statuses; replies and links are dropped.
const old = new Database(":memory:");
for (const sql of migrations.slice(0, 7)) old.exec(sql);
old.exec("INSERT INTO documents VALUES('d','ctx','p.md',0,'v',5)");
for (const [i, status] of ["draft", "sent", "replied", "resolved"].entries()) old.prepare("INSERT INTO comments VALUES(?, 'd', ?, ?, '{\"kind\":\"doc\"}', 'b', NULL)").run(`c${i}`, i, status);
for (const sql of migrations.slice(7)) old.exec(sql);
assert.deepEqual(new Store(old).comments("d").map(c => c.status), ["open", "sent", "sent", "closed"]);
assert.equal(old.prepare("SELECT count(*) AS n FROM sqlite_master WHERE name IN ('replies','links')").get().n, 0);
old.close();
console.log("Store: open/sent/closed, delete, generations, independent archives, status migration, locale keys and language resolution OK.");
