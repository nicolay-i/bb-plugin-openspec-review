import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdir, mkdtemp, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";
import { windowsCliCommand } from "../src/windows-cli.ts";
const base = resolve(".tmp/windows-cli"); await mkdir(base, { recursive: true });
const root = await mkdtemp(join(base, "npm prefix & spaces-"));
const entry = join(root, "node_modules/@fission-ai/openspec/bin/openspec.js");
await mkdir(join(root, "node_modules/@fission-ai/openspec/bin"), { recursive: true });
await writeFile(join(root, "openspec.cmd"), "@echo this launcher must never run");
await writeFile(entry, "console.log(JSON.stringify(process.argv.slice(2)))");
const args = ["status", "--change", "x & echo unsafe", "--json"];
const command = await windowsCliCommand(args, [join(root, "missing"), `"${root}"`]);
assert.equal(command.executable, process.execPath);
assert.deepEqual(JSON.parse(execFileSync(command.executable, command.args, { encoding: "utf8" })), args);
await assert.rejects(() => windowsCliCommand([], [join(root, "missing")]), /cli_missing/);
const broken = join(root, "broken"); await mkdir(broken); await writeFile(join(broken, "openspec.cmd"), "");
await assert.rejects(() => windowsCliCommand([], [broken, root]), /unsupported_cli_installation/, "never silently skip a broken first installation");
console.log("Windows CLI: npm JS entrypoint, spaces/metacharacters, missing CLI and broken-first-installation refusal OK.");
